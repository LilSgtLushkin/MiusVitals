#!/usr/bin/env python3
"""Add/remove the one import used by MiusVitals.

The input must be one of the three byte-for-byte known MiusPlayer v20 modules:
  python patch_import.py basic_network.codelib out.codelib
  python patch_import.py rebased.codelib out.codelib
  python patch_import.py --unpatch out.codelib restored.codelib

Patching only adds PE section ``.mpimp`` with the import
``mp_vitals.dll!MpVitalsInit``. It does not alter existing code or data.  The
unpatch operation is deliberately restricted to an artifact generated by this
script and restores its exact known input.
"""
import hashlib
import struct
import sys

V20_SIZE = 377344
V20_TIMESTAMP = 0x6ACFAA3D
DLL, FUNC = b"mp_vitals.dll", b"MpVitalsInit"

# Hash -> (description, expected patched hash).  Rebase leaves the PE layout and
# original import table intact, so all three use the same safe append operation.
KNOWN_INPUTS = {
    "8108bd1e9af8080ef8b1050512b8311848f5a336acb49a7479388733b4ae5723":
        ("MiusPlayer v20 original", "d2e34581b42d0573547e221873d7538b64a413267e8ed388abeb46dd42b630d2"),
    # v7.1.1 release inputs remain accepted so its artifacts can still be cleanly
    # unpatched, but v7.2's release builder produces the two target-verified map
    # variants immediately below.
    "603fb40567e0094a1dd0136df927196d76efea5dd43a364e7f470664117da272":
        ("v20 rebased for 3598/1 (v7.1.1 with Start)", "7caf36cddabf7eb388a3c6c393b05733e051955d63d32ef13531ce88004dcfba"),
    "c270f40ae49ef6922eeaf837f748ef622ba9a55fbf045b8ae1f92e9af689231d":
        ("v20 rebased for 3598/1 (v7.1.1 without Start)", "2fb049b9b465de2e05bd9bbe7d5573a772319cc4d65fb20bb146e648a7cdf8ec"),
    "af9f67950d04d2323aeb98dfd7beb40ffff1af7e2f211fd2647ccd783282fd1e":
        ("v20 rebased for 3598/1 (v7.2 with Start and operation-map detour)", "4c91874c4b62db424ecca36586121bcb3b4cc7849cc900285e68de5151eddc36"),
    "d16680f50aa31aafcbc4f4e9a8acfaaa3f34f9e34d3514c67ac816c875fc8612":
        ("v20 rebased for 3598/1 (v7.2 without Start and with operation-map detour)", "f0766bec48696869d59d4a654a04f20bd7baf9f73adb6fbf139e7da31dfc1f4f"),
}
PATCHED_TO_INPUT = {patched: source for source, (_, patched) in KNOWN_INPUTS.items()}

# These are invariant in all three permitted inputs. They are restored by
# --unpatch after the appended section has been removed.
ORIGINAL_IMPORT_RVA = 0x58344
ORIGINAL_IMPORT_SIZE = 0x154


def align(value, boundary):
    return (value + boundary - 1) // boundary * boundary


def pe_info(data):
    if len(data) < 0x100 or data[:2] != b"MZ":
        raise ValueError("not a PE file")
    pe, = struct.unpack_from("<I", data, 0x3C)
    if pe + 24 > len(data) or data[pe:pe + 4] != b"PE\0\0":
        raise ValueError("not a PE file")
    machine, nsec, timestamp, _, _, opt_size, _ = struct.unpack_from("<HHIIIHH", data, pe + 4)
    if machine != 0x8664 or timestamp != V20_TIMESTAMP:
        raise ValueError("not the MiusPlayer v20 x64 module")
    opt = pe + 24
    if struct.unpack_from("<H", data, opt)[0] != 0x20B:
        raise ValueError("not PE32+")
    sect_align, file_align = struct.unpack_from("<II", data, opt + 32)
    size_image, size_headers = struct.unpack_from("<II", data, opt + 56)
    section_table = pe + 24 + opt_size
    if section_table + 40 * nsec > len(data):
        raise ValueError("truncated section table")
    sections = []
    for index in range(nsec):
        at = section_table + 40 * index
        name = bytes(data[at:at + 8]).rstrip(b"\0")
        virtual_size, virtual_address, raw_size, raw_ptr = struct.unpack_from("<IIII", data, at + 8)
        sections.append((name, virtual_size, virtual_address, raw_size, raw_ptr))
    return {
        "pe": pe, "opt": opt, "nsec": nsec, "sect_align": sect_align,
        "file_align": file_align, "size_image": size_image, "size_headers": size_headers,
        "section_table": section_table, "sections": sections,
    }


def patch(source):
    source_hash = hashlib.sha256(source).hexdigest()
    if source_hash not in KNOWN_INPUTS:
        raise ValueError("SHA-256 is not an accepted v20 input: " + source_hash)
    if len(source) != V20_SIZE:
        raise ValueError("unexpected v20 module size")
    info = pe_info(source)
    data = bytearray(source)
    sections = info["sections"]
    if any(section[0] == b".mpimp" for section in sections):
        raise ValueError("already patched")
    if info["section_table"] + 40 * (info["nsec"] + 1) > info["size_headers"] or any(
        raw_ptr and raw_ptr < info["section_table"] + 40 * (info["nsec"] + 1)
        for _, _, _, _, raw_ptr in sections
    ):
        raise ValueError("no room for another section header")

    ddir = info["opt"] + 112
    import_rva, import_size = struct.unpack_from("<II", data, ddir + 8)

    def rva_to_offset(rva):
        for _, virtual_size, virtual_address, raw_size, raw_ptr in sections:
            if virtual_address <= rva < virtual_address + max(virtual_size, raw_size):
                return raw_ptr + rva - virtual_address
        raise ValueError("bad import RVA %#x" % rva)

    old_offset = rva_to_offset(import_rva)
    old = bytes(data[old_offset:old_offset + import_size])
    old_descriptors = 0
    while old_descriptors * 20 + 20 <= len(old) and any(old[old_descriptors * 20:old_descriptors * 20 + 20]):
        old_descriptors += 1
    if old_descriptors == 0:
        raise ValueError("empty import table")
    old = old[:old_descriptors * 20]

    new_va = align(max(va + max(vsize, raw_size) for _, vsize, va, raw_size, _ in sections), info["sect_align"])
    descriptor_len = (old_descriptors + 2) * 20
    ilt = new_va + descriptor_len
    iat = ilt + 16
    hint_name = iat + 16
    dll_name = hint_name + 2 + len(FUNC) + 1 + ((2 + len(FUNC) + 1) & 1)

    blob = bytearray(old)
    blob += struct.pack("<IIIII", ilt, 0, 0, dll_name, iat)
    blob += b"\0" * 20
    blob += struct.pack("<QQ", hint_name, 0)  # ILT
    blob += struct.pack("<QQ", hint_name, 0)  # IAT; overwritten by loader
    blob += struct.pack("<H", 0) + FUNC + b"\0"
    if len(blob) + new_va != dll_name:
        blob += b"\0" * (dll_name - new_va - len(blob))
    blob += DLL + b"\0"

    raw_size = align(len(blob), info["file_align"])
    raw_ptr = align(len(data), info["file_align"])
    data += b"\0" * (raw_ptr - len(data))
    data += blob + b"\0" * (raw_size - len(blob))

    header = info["section_table"] + 40 * info["nsec"]
    data[header:header + 40] = struct.pack(
        "<8sIIIIIIHHI", b".mpimp", len(blob), new_va, raw_size, raw_ptr, 0, 0, 0, 0, 0xC0000040
    )
    struct.pack_into("<H", data, info["pe"] + 6, info["nsec"] + 1)
    struct.pack_into("<I", data, info["opt"] + 56, align(new_va + len(blob), info["sect_align"]))
    initialized, = struct.unpack_from("<I", data, info["opt"] + 8)
    struct.pack_into("<I", data, info["opt"] + 8, initialized + raw_size)
    struct.pack_into("<II", data, ddir + 8, new_va, descriptor_len)
    struct.pack_into("<II", data, ddir + 11 * 8, 0, 0)  # no bound imports

    result = bytes(data)
    expected = KNOWN_INPUTS[source_hash][1]
    actual = hashlib.sha256(result).hexdigest()
    if actual != expected:
        raise ValueError("patched module hash differs from the canonical result: " + actual)
    return result


def unpatch(source):
    source_hash = hashlib.sha256(source).hexdigest()
    expected_input = PATCHED_TO_INPUT.get(source_hash)
    if not expected_input:
        raise ValueError("SHA-256 is not a MiusVitals artifact: " + source_hash)
    info = pe_info(source)
    if info["nsec"] < 2:
        raise ValueError("bad section count")
    name, _, new_va, raw_size, raw_ptr = info["sections"][-1]
    if name != b".mpimp" or raw_ptr + raw_size != len(source):
        raise ValueError("unexpected MiusVitals section")
    ddir = info["opt"] + 112
    import_rva, _ = struct.unpack_from("<II", source, ddir + 8)
    if import_rva != new_va:
        raise ValueError(".mpimp is not the active import table")

    data = bytearray(source[:raw_ptr])
    last_header = info["section_table"] + 40 * (info["nsec"] - 1)
    data[last_header:last_header + 40] = b"\0" * 40
    struct.pack_into("<H", data, info["pe"] + 6, info["nsec"] - 1)
    previous_end = max(va + max(vsize, section_raw_size)
                       for _, vsize, va, section_raw_size, _ in info["sections"][:-1])
    struct.pack_into("<I", data, info["opt"] + 56, align(previous_end, info["sect_align"]))
    initialized, = struct.unpack_from("<I", data, info["opt"] + 8)
    struct.pack_into("<I", data, info["opt"] + 8, initialized - raw_size)
    struct.pack_into("<II", data, ddir + 8, ORIGINAL_IMPORT_RVA, ORIGINAL_IMPORT_SIZE)
    struct.pack_into("<II", data, ddir + 11 * 8, 0, 0)

    result = bytes(data)
    actual = hashlib.sha256(result).hexdigest()
    if actual != expected_input:
        raise ValueError("unpatched module hash differs from canonical input: " + actual)
    return result


def main(argv):
    unpatch_mode = len(argv) == 4 and argv[1] == "--unpatch"
    if not ((len(argv) == 3) or unpatch_mode):
        raise SystemExit(__doc__)
    source_name, output_name = argv[-2:]
    source = open(source_name, "rb").read()
    try:
        result = unpatch(source) if unpatch_mode else patch(source)
    except ValueError as error:
        raise SystemExit(str(error))
    with open(output_name, "wb") as output:
        output.write(result)
    print("written", output_name, len(result), "bytes, sha256", hashlib.sha256(result).hexdigest())


if __name__ == "__main__":
    main(sys.argv)
