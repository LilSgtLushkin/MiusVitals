static Object *humans[2];
static bool is_host;
static unsigned own_hits, remote_hits;
static bool replay_valid;
static uintptr_t hit_original(Object *target, void *record, u32 kind, Object *, u32 value, bool last)
{
    if (session_owns(target)) { ++own_hits; return 1; }
    ++remote_hits;
    u32 seed = 0, part = 0;
    memcpy(&seed, (char *)target + 0x2768, 4); memcpy(&part, (char *)record + 0x60, 4);
    // Host's local component numbers: 10,20; joiner's: 30,40. Each hit is generated by
    // the other process, then translated to this process's component number.
    u32 expected_group = is_host ? 20 : 30;
    u32 expected_seed = is_host ? 2222 : 1111;
    u32 expected_kind = is_host ? 200 : 100;
    replay_valid = target == humans[is_host ? 1 : 0] && seed == expected_seed && part == ((expected_group << 10) | 7) &&
                   kind == expected_kind && value == expected_kind + 1 && last;
    return 1;
}
static uintptr_t group_set(Object *, u32, const char *) { return 1; }
static uintptr_t scalar_set(Object *, u32, u32) { return 0; }
static void put32(void *p, u32 v) { memcpy(p, &v, 4); }

int main(int argc, char **argv)
{
    if (argc != 4) return 2;
    bool host = !strcmp(argv[1], "host"), join = !strcmp(argv[1], "join");
    if (!host && !join) return 2;
    is_host = host;
    bool steam = GetEnvironmentVariableA("EVENT_FAKE_STEAM", nullptr, 0) != 0;
    SetEnvironmentVariableA("MP_ROLE", host ? "host" : "join");
    SetEnvironmentVariableA("MP_HOST_MODE", "operation");
    SetEnvironmentVariableA("MP_STEAM", steam ? nullptr : "0");
    SetEnvironmentVariableA("MP_STEAM_FAKE", steam ? argv[2] : nullptr);
    SetEnvironmentVariableA("MP_PORT", host ? argv[2] : "0");
    SetEnvironmentVariableA("MP_VITALS", "0");
    SetEnvironmentVariableA("MP_MAP", nullptr);
    char address[80]; sprintf_s(address, steam ? "steam:%s" : "127.0.0.1:%s", argv[3]);
    SetEnvironmentVariableA("MP_PEER", address);
    session_test_disable_upnp(true); session_test_disable_udp(steam); session_test_event_faults();

    alignas(8) unsigned char manager[0x1800] = {}, h1[0x3000] = {}, h2[0x3000] = {},
        parts1[0x60] = {}, parts2[0x60] = {}, anim_memory[0x300] = {}, instances[0x280] = {}, group[128] = {};
    void *manager_vt[58] = {}; manager_vt[9] = (void *)find_nothing; manager_vt[56] = (void *)desc_id; manager_vt[57] = (void *)desc_ptr;
    ObjMan *om = (ObjMan *)manager; om->vtbl = manager_vt;
    humans[0] = (Object *)h1; humans[1] = (Object *)h2;
    unsigned char *part_rows[] = {parts1, parts2};
    Object *list[] = {humans[0], humans[1]};
    Object **list_ptr = list; memcpy(manager + 0xf0, &list_ptr, 8); put32(manager + 0xfc, 2);
    for (unsigned i = 0; i < 2; ++i) {
        Object *o = humans[i]; o->objman = om; o->iface = "i_human";
        sprintf_s(o->full, "i_human:human_%08x", i + 1);
        put32((char *)o + 0x1d60, i);
        unsigned char *row = part_rows[i]; memcpy((char *)o + 0x850, &row, 8); put32((char *)o + 0x85c, 1);
        u32 high = (host ? 10 : 30) + i * 10;
        put32(row + 0x48, (high << 10) | 7);
        put32((char *)o + 0x2768, i == (host ? 0u : 1u) ? (host ? 1111 : 2222) : 0);
    }
    Object *anim = (Object *)anim_memory; anim->objman = om;
    void *table_storage[42] = {}; void **avt = table_storage + 1; avt[4] = (void *)scalar_set; avt[11] = (void *)group_set;
    anim->vtbl = avt; unsigned char *inst_ptr = instances; memcpy(anim_memory + 0x140, &inst_ptr, 8);
    strcpy_s((char *)group, sizeof group, "walk"); put32(group + 0x3e + 12, 8);
    void *group_ptr = group + 0x3e;
    for (unsigned i = 0; i < 2; ++i) {
        unsigned char *row = instances + i * 0x140;
        memcpy(row + 0x70, &group_ptr, 8); put32(row + 0x104, 1); put32(row + 0x10c, 1);
    }
    unsigned mine = host ? 0 : 1, remote = host ? 1 : 0;
    put32(instances + mine * 0x140 + 0xa8, host ? 101 : 202);
    u64 my_key = (2ull << 32) | (mine + 1);
    char name[128]; const char *host_port = host ? argv[2] : argv[3];
    sprintf_s(name, "Local\\netv21_event_ready_%s_%s", steam ? "steam" : "ip", host_port);
    HANDLE ready = CreateEventA(nullptr, TRUE, FALSE, name);
    sprintf_s(name, "Local\\netv21_event_first_host_%s_%s", steam ? "steam" : "ip", host_port);
    HANDLE first_host = CreateEventA(nullptr, TRUE, FALSE, name);
    sprintf_s(name, "Local\\netv21_event_first_join_%s_%s", steam ? "steam" : "ip", host_port);
    HANDLE first_join = CreateEventA(nullptr, TRUE, FALSE, name);
    sprintf_s(name, "Local\\netv21_event_rekey_host_%s_%s", steam ? "steam" : "ip", host_port);
    HANDLE rekey_host = CreateEventA(nullptr, TRUE, FALSE, name);
    sprintf_s(name, "Local\\netv21_event_rekey_join_%s_%s", steam ? "steam" : "ip", host_port);
    HANDLE rekey_join = CreateEventA(nullptr, TRUE, FALSE, name);
    sprintf_s(name, "Local\\netv21_event_host_%s_%s", steam ? "steam" : "ip", host_port);
    HANDLE host_done = CreateEventA(nullptr, TRUE, FALSE, name);
    sprintf_s(name, "Local\\netv21_event_join_%s_%s", steam ? "steam" : "ip", host_port);
    HANDLE join_done = CreateEventA(nullptr, TRUE, FALSE, name);
    if (!ready || !first_host || !first_join || !rekey_host || !rekey_join || !host_done || !join_done) return 3;
    session_start(om); session_note_phase(2); session_test_owned(my_key);
    shots_test_engine(om, (char *)om, launch); hits_test_engine(om, hit_original, hit_original); anim_test_engine(om, anim);
    if (host) SetEvent(ready); else if (WaitForSingleObject(ready, 5000) != WAIT_OBJECT_0) return 4;
    auto emit_hit = [&]() {
        unsigned char hit[0x80] = {};
        u32 high = (host ? 10 : 30) + mine * 10;
        put32(hit + 0x60, (high << 10) | 7);
        u32 kind = host ? 100 : 200;
        hits_test_capture(false, humans[mine], hit, kind, nullptr, kind + 1, true);
    };
    auto signalled = [](HANDLE event) { return WaitForSingleObject(event, 0) == WAIT_OBJECT_0; };
    bool first_sent = false, interrupted = false, reconnected = false, first_ok = false;
    bool changed = false, rekeyed = false, second_sent = false, local_ok = false;
    bool capability_tested = false, capability_risk_seen = false;
    u32 first_local = 0, first_peer = 0, first_stream = 0;
    DWORD started = GetTickCount(), first_stable = 0, second_stable = 0;
    while ((DWORD)(GetTickCount() - started) < 21000) {
        DWORD now = GetTickCount();
        session_frame(om); session_test_owned(my_key); session_sim_step(om, 16);
        bool features = session_connected() && (session_peer_features() & PEER_FEATURES) == PEER_FEATURES && session_unit(my_key);
        if (host && features && !capability_tested) {
            capability_tested = true;
            capability_risk_seen = session_test_event_capability_reorder();
            // Wait for the next real Hello to restore the peer's current advertisement.
            features = false;
            printf("capability reordering characterization: stale OFF/ON accepted=%d (risk remains OPEN)\n", (int)capability_risk_seen);
        }
        if (!first_sent && features) {
            first_local = vitals_epoch(); first_peer = vitals_peer_epoch(); first_stream = shots_test_epoch();
            emit_hit(); first_sent = true;
        }
        if (host && first_sent && !interrupted) {
            // Simulate the timeout path while the event is still queued; the same peer must
            // reconnect without throwing away that unacknowledged ordered stream.
            session_test_event_disconnect(); interrupted = true;
        } else if (host && interrupted && session_connected()) reconnected = true;
        u32 animation = 0; memcpy(&animation, instances + remote * 0x140 + 0xa8, 4);
        bool pass1 = first_sent && own_hits == 1 && remote_hits == 1 && replay_valid &&
                     animation == (host ? 202u : 101u) && (!host || reconnected) &&
                     session_test_event_dropped() && session_test_event_duplicates() && session_test_event_ack_dropped();
        if (pass1 && !first_stable) first_stable = now ? now : 1;
        if (pass1 && first_stable && (DWORD)(now - first_stable) >= 1000 && !first_ok) {
            first_ok = true; SetEvent(host ? first_host : first_join);
        }
        if (first_ok && signalled(first_host) && signalled(first_join)) {
            if (!changed) {
                changed = true;
                if (join) vitals_start(); // model a new local process identity, not a real process restart
            }
            bool new_identity = host ? (first_peer && vitals_peer_epoch() && vitals_peer_epoch() != first_peer) :
                                       (vitals_epoch() != first_local && vitals_peer_epoch() && shots_test_epoch() != first_stream);
            if (new_identity && !rekeyed) { rekeyed = true; SetEvent(host ? rekey_host : rekey_join); }
            if (rekeyed && signalled(rekey_host) && signalled(rekey_join) && features && !second_sent) {
                emit_hit(); second_sent = true;
            }
        }
        bool pass2 = second_sent && own_hits == 2 && remote_hits == 2 && replay_valid &&
                     animation == (host ? 202u : 101u);
        if (pass2 && !second_stable) second_stable = now ? now : 1;
        if (pass2 && second_stable && (DWORD)(now - second_stable) >= 1000 && !local_ok) {
            local_ok = true; SetEvent(host ? host_done : join_done);
        }
        if (local_ok && signalled(host_done) && signalled(join_done)) break;
        Sleep(10);
    }
    bool both = signalled(host_done) && signalled(join_done);
    bool ok = local_ok && both && remote_hits == 2 && (!host || (capability_tested && capability_risk_seen));
    u32 animation = 0; memcpy(&animation, instances + remote * 0x140 + 0xa8, 4);
    printf("EVENT_%s_RESULT %s ok=%d hit=%u replay=%d anim=%u drop=%u duplicate=%u ack_drop=%u reconnect=%d rekey=%d second=%d stale_capability=%d waiting=%zu\n",
           steam ? "STEAM" : "IP", host ? "host" : "join", (int)ok, remote_hits, (int)replay_valid, animation,
           session_test_event_dropped(), session_test_event_duplicates(), session_test_event_ack_dropped(),
           (int)(!host || reconnected), (int)rekeyed, (int)second_sent, (int)(host && capability_risk_seen), shots_test_outstanding());
    session_stop(); steam_shutdown();
    CloseHandle(ready); CloseHandle(first_host); CloseHandle(first_join); CloseHandle(rekey_host); CloseHandle(rekey_join);
    CloseHandle(host_done); CloseHandle(join_done);
    return ok ? 0 : 1;
}
