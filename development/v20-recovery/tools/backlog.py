#!/usr/bin/env python3
"""Turn the v20 classification into a port backlog, grouped by milestone.

`v20tool.py classify` answers "what is in v20".  This answers "what do we pick up next", and in
what order: every function that is not SAME becomes a line item, filed under the milestone it
belongs to (see docs/V20_SOURCE_RECOVERY.md, section 6) and with the strings it prints, because a
function's log lines are usually a better name than the mangled symbol.

    python3 development/v20-recovery/tools/backlog.py [--csv PATH] [--out PATH]
"""
from __future__ import annotations

import argparse
import csv
import re
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
DEFAULT_CSV = ROOT / "reports" / "v20-functions.csv"
DEFAULT_OUT = ROOT / "reports" / "v20-backlog.md"

# Milestones, in the order they are worked on.  A function is filed under the first milestone whose
# pattern matches any of its strings; leftovers go last so they cannot silently disappear.
MILESTONES = [
    ("M2", "Steam", re.compile(
        r"steam|MP_STEAM|rich presence|gtmf_join|P2P|friends", re.I)),
    ("M4", "Lobby and forces", re.compile(
        r"lobby|MULTIPLAYER|force|cfgpack|battle setup|MP_BATTLE_SETUP|skirmish|resign|MP_AUTOJOIN", re.I)),
    ("M5", "Operation map", re.compile(
        r"map:|opgame|opsave|sidecar|_known|MP_MAP|operation|_known_|adv_opmap|formation", re.I)),
    ("M3", "Battle synchronization", re.compile(
        r"ceasefire|MP_SYNC|MP_END|hit:|crater|trench|shot|shots|clock|anim|"
        r"MP_HIT|MP_CRATER|MP_TRENCH|MP_SHOTS|trace: battle|MP_APPLY_DELAY|MP_TEST_TRACE|"
        r"net:|session|battle|transform|shellphys|sync|stamp|MP_ROLE|MP_PEER|MP_VERSUS", re.I)),
    ("M6", "Tests and tooling", re.compile(
        r"MP_TEST|mp_cmd_|mp_join|MP_LOG|log_", re.I)),
]

PROJECT = ("@opsave@", "@Joiner@", "@Sidecar@", "lambda_")


def kind(row: dict[str, str]) -> str:
    """SAME / CHANGED / NEW-{logic,stl,plumbing,unknown} - what the port has to do with it."""
    name = row["v12_name"]
    if row["status"] == "SAME":
        return "SAME"
    if row["status"] == "CHANGED":
        return "CHANGED"
    if not name.strip():
        return "NEW:unknown"
    if name.startswith("??__"):
        return "NEW:plumbing"
    if "@std@@" in name and not any(p in name for p in PROJECT):
        return "NEW:stl"
    return "NEW:logic"


def milestone(row: dict[str, str]) -> tuple[str, str]:
    """File by what the function prints; fall back to what it is called when it prints nothing."""
    for tag, label, pattern in MILESTONES:
        if pattern.search(row["strings"]):
            return tag, label
    if not row["strings"].strip():
        for tag, label, pattern in MILESTONES:
            if pattern.search(row["v12_name"]):
                return tag, label
        if int(row["size"]) < 128:
            return "M8", "Small deltas (<128 bytes, no log lines): one-liners to diff, not to design"
    return "M7", "Unsorted"


def short(name: str, limit: int = 78) -> str:
    """Mangled names are a wall of text; keep the readable head of the symbol."""
    if not name.strip():
        return "—"
    head = re.sub(r"\$\$?[A-Z]?\$?[^@]*@", "", name)
    head = name.split("@")[0].lstrip("?")
    return head[:limit]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--csv", type=Path, default=DEFAULT_CSV)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()

    rows = list(csv.DictReader(args.csv.open(newline="")))
    todo = [r for r in rows if kind(r) != "SAME"]
    kinds: dict[str, list[int]] = defaultdict(lambda: [0, 0])
    for row in rows:
        k = kind(row)
        kinds[k][0] += 1
        kinds[k][1] += int(row["size"])

    by_ms: dict[tuple[str, str], list[dict[str, str]]] = defaultdict(list)
    for row in todo:
        by_ms[milestone(row)].append(row)

    out = [
        "# v20 port backlog",
        "",
        "Generated by `tools/backlog.py` from `reports/v20-functions.csv`. Do not edit by hand.",
        "",
        f"{len(rows)} functions, {sum(int(r['size']) for r in rows)} bytes of code; "
        f"{len(todo)} are not identical to the published source and therefore become work items.",
        "",
        "| kind | functions | bytes | who does it |",
        "|---|---|---|---|",
        f"| SAME | {kinds['SAME'][0]} | {kinds['SAME'][1]} | nobody: the v12 source is that code already |",
        f"| CHANGED | {kinds['CHANGED'][0]} | {kinds['CHANGED'][1]} | take the v12 function, apply the delta |",
        f"| NEW:logic | {kinds['NEW:logic'][0]} | {kinds['NEW:logic'][1]} | write from the decompiled pseudo-C |",
        f"| NEW:unknown | {kinds['NEW:unknown'][0]} | {kinds['NEW:unknown'][1]} | read the pseudo-C first, then name and write |",
        f"| NEW:stl | {kinds['NEW:stl'][0]} | {kinds['NEW:stl'][1]} | compiler output: comes back by itself when the source is rebuilt |",
        f"| NEW:plumbing | {kinds['NEW:plumbing'][0]} | {kinds['NEW:plumbing'][1]} | static initializers and atexit thunks: same, compiler output |",
        "",
        "`similarity` is the structural match against the nearest v12 function. Anything below ~0.5 is",
        "a guess: the name column is a hint, not a fact. Names in the tables below are hints too;",
        "the string column is what the function actually does.",
        "",
    ]

    order = MILESTONES + [("M8", "Small deltas (<128 bytes, no log lines): one-liners to diff, not to design", None), ("M7", "Unsorted", None)]
    for tag, label, _ in order:
        items = by_ms.get((tag, label), [])
        if not items:
            continue
        items.sort(key=lambda r: -int(r["size"]))
        total = sum(int(r["size"]) for r in items)
        out += [f"## {tag} — {label}: {len(items)} functions, {total} bytes", ""]
        out.append("| RVA | bytes | kind | nearest v12 name (hint) | strings |")
        out.append("|---|---|---|---|---|")
        for row in items:
            strings = row["strings"].replace("|", "\\|")[:160]
            out.append(
                f"| `{row['rva']}` | {row['size']} | {kind(row).replace('NEW:', 'new ')} "
                f"| `{short(row['v12_name'])}` | {strings} |")
        out.append("")

    args.out.write_text("\n".join(out) + "\n")
    print(f"wrote {args.out}: {len(todo)} work items in "
          f"{sum(1 for k in by_ms if by_ms[k])} milestones")


if __name__ == "__main__":
    main()
