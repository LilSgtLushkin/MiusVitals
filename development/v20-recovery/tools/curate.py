#!/usr/bin/env python3
"""Copy the decompilation worth reading into `reports/decomp/`, with an index.

`work/decomp/` holds all 895 functions and is not committed: most of it is STL instantiations
and one-line thunks, it is reproducible, and it would bury the part a person actually reads.

What is committed:

  * every function the backlog lists (i.e. everything that is not identical to the published
    source) and that is at least --min-size bytes - the code the port has to write,
  * plus `--all` to take everything (for an audit of a specific area).

    python3 development/v20-recovery/tools/curate.py           # refresh reports/decomp
    python3 development/v20-recovery/tools/curate.py --all
"""
from __future__ import annotations

import argparse
import csv
import re
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
WORK = ROOT / "work"
DECOMP = WORK / "decomp"
TARGET = ROOT / "reports" / "decomp"
CSV = ROOT / "reports" / "v20-functions.csv"

from rules import VERIFIED, is_compiler_output, milestone  # noqa: E402  (sits next to this file)





def safe(name: str) -> str:
    name = name.split("@@")[0].lstrip("?")
    name = re.sub(r"[^A-Za-z0-9_.-]+", "-", name).strip("-")
    return name[:48] or "unnamed"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--min-size", type=int, default=256)
    ap.add_argument("--all", action="store_true")
    args = ap.parse_args()

    rows = {int(r["rva"], 16): r for r in csv.DictReader(CSV.open(newline=""))}
    if TARGET.exists():
        shutil.rmtree(TARGET)
    TARGET.mkdir(parents=True)

    files = {}
    for path in DECOMP.glob("*.c"):
        try:
            files[int(path.name.split("_")[0], 16)] = path
        except ValueError:
            continue

    picked = []
    for rva, row in sorted(rows.items()):
        if rva not in files:
            continue
        if not args.all and (row["status"] == "SAME" or int(row["size"]) < args.min_size
                             or is_compiler_output(row)):
            continue
        try:
            similarity = float(row["similarity"] or 0)
        except ValueError:
            similarity = 0.0
        # Name the file after the symbol only when the match is strong; a 0.3 "match" is noise.
        label = VERIFIED.get(rva) or (safe(row["v12_name"]) if similarity >= 0.5 else "unnamed")
        target = TARGET / f"{rva:06x}_{label}.c"
        shutil.copyfile(files[rva], target)
        picked.append((rva, row, target.name))

    by_stage: dict[str, list] = {}
    for rva, row, name in picked:
        by_stage.setdefault(milestone(row)[0], []).append((rva, row, name))

    index = [
        "# Decompilation of v20",
        "",
        "Generated by `tools/curate.py` from `work/decomp/` (which is not committed). These are the",
        f"functions the port has to write: {len(picked)} of 895, at least {args.min_size} bytes and",
        "not identical to the published v12 source. Read them next to the matching v12 function: the",
        "pseudo-C says what the code does, the v12 source says how this codebase writes it.",
        "",
        "String literals are substituted back in by `tools/polish.py`, so most log lines appear",
        "verbatim. `g_XXXX` are globals at that RVA (`v20.codelib` is loaded at 0, so RVA = address);",
        "`sub_XXXX` are calls angr could not name. `hint` is the nearest v12 symbol: a lead, not a",
        "fact — below ~0.5 similarity it is often wrong (that is why the verified names are in",
        "`tools/rules.py` and the files are named after them).",
        "",
        "| stage | files | bytes of original code |",
        "|---|---|---|",
    ]
    for tag in sorted(by_stage):
        items = by_stage[tag]
        index.append(f"| {tag} | {len(items)} | {sum(int(r['size']) for _, r, _ in items)} |")
    index.append("")

    for tag in sorted(by_stage):
        label = {"M2": "Steam", "M3": "Battle synchronization", "M4": "Lobby and forces",
                 "M5": "Operation map", "M6": "Tests and tooling"}.get(tag, "Unsorted")
        index += [f"## {tag} — {label}", ""]
        for rva, row, name in sorted(by_stage[tag], key=lambda x: -int(x[1]["size"])):
            shown = row["strings"].replace("|", "\\|")[:110]
            hint = safe(row["v12_name"]) if row["v12_name"].strip() else "—"
            if rva in VERIFIED:
                hint = "verified"
            else:
                hint = f"{hint} ({similarity:.2f})"
            index.append(f"* [`{rva:06x}`]({name}) — {row['size']} B, {row['status'].lower()}, "
                         f"hint `{hint}`" + (f" — {shown}" if shown else ""))
        index.append("")

    (TARGET / "README.md").write_text("\n".join(index) + "\n")
    print(f"curated {len(picked)} files into {TARGET}")
    for tag in sorted(by_stage):
        print(f"  {tag}: {len(by_stage[tag])}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
